const humanizeCode = (code) => {
  const words = code
    .replace(/^Error\./, "")
    .replace(/([a-z0-9])([A-Z])/g, "$1 $2")
    .replace(/([A-Z]+)([A-Z][a-z])/g, "$1 $2")
    .replaceAll("_", " ")
    .trim();
  if (!words) return null;
  return `${words.charAt(0).toUpperCase()}${words.slice(1).toLowerCase()}.`;
};

export const getErrorCodeMessage = (code, fallback = null) => {
  if (typeof code !== "string" || !code.trim()) return fallback;
  return ERROR_CODE_MESSAGES[code] ?? humanizeCode(code) ?? fallback;
};
